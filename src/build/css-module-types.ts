import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * The class names a CSS module exports, as the keys Vite produces for it with
 * `localsConvention: 'camelCaseOnly'`. Selectors inside `:global()` belong to
 * other stylesheets and are left out.
 */
export function cssModuleClassKeys(css: string): string[] {
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const withoutGlobals = withoutComments.replace(/:global\([^)]*\)/g, '');
  const keys = new Set<string>();

  for (const match of withoutGlobals.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) {
    keys.add(camelCase(match[1]));
  }

  return [...keys].sort();
}

export function cssModuleDeclaration(css: string): string {
  const lines = cssModuleClassKeys(css).map((key) => `  readonly ${key}: string;`);

  return `// Generated by \`npm run css:types\` from the stylesheet next to it. Do not edit.
declare const styles: {
${lines.join('\n')}
};

export default styles;
`;
}

// Matches the transform Vite applies (postcss-modules' camelCase): every run of
// non-alphanumerics is a word boundary.
function camelCase(name: string): string {
  return name
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((word, index) => (index === 0 ? word : word[0].toUpperCase() + word.slice(1)))
    .join('');
}

export const CSS_MODULES = ['src/ui/components/layout/layout.module.css'];

export function declarationPath(cssPath: string): string {
  return `${cssPath}.d.ts`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const cssPath of CSS_MODULES) {
    writeFileSync(declarationPath(cssPath), cssModuleDeclaration(readFileSync(cssPath, 'utf8')));
  }
}
